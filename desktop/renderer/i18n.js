    function normalizeLanguage(value) {
        return String(value ?? '').toLowerCase().startsWith('en') ? 'en' : 'pl';
    }

    function t(language, key, vars = {}) {
        const dict = MESSAGES[normalizeLanguage(language)] ?? MESSAGES.pl;
        const template = dict[key] ?? MESSAGES.pl[key] ?? key;
        return String(template).replace(/\{(\w+)\}/g, (match, name) => (
            Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
        ));
    }

    const api = {MESSAGES, normalizeLanguage, t};

    if (typeof module !== 'undefined' && module.exports) {
        module.exports = api;
    }
    if (root) {
        root.instalingI18n = api;
    }
