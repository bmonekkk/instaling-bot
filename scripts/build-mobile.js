#!/usr/bin/env node
// Bundles the shared mobile engine into the userscript and the native shells.
// Run: npm run build:mobile

const fs = require('fs/promises');
const path = require('path');
const esbuild = require('esbuild');

const ROOT = path.resolve(__dirname, '..');
const pkg = require(path.join(ROOT, 'package.json'));

const USERSCRIPT_HEADER = `// ==UserScript==
// @name         instaling-bot
// @namespace    https://github.com/bmonekkk/instaling-bot
// @version      ${pkg.version}
// @description  Human-like bot for instaling.pl (PL/EN). Shared engine with the desktop app.
// @author       bmonekkk
// @match        https://instaling.pl/*
// @match        https://www.instaling.pl/*
// @match        https://*.instaling.pl/*
// @grant        GM_getValue
// @grant        GM_setValue
// @run-at       document-idle
// @updateURL    https://github.com/bmonekkk/instaling-bot/releases/latest/download/instaling-bot.user.js
// @downloadURL  https://github.com/bmonekkk/instaling-bot/releases/latest/download/instaling-bot.user.js
// ==/UserScript==
`;

async function build(entry, outfile, {banner, globalName, defines = {}} = {}) {
    await fs.mkdir(path.dirname(outfile), {recursive: true});
    await esbuild.build({
        entryPoints: [entry],
        outfile,
        bundle: true,
        format: 'iife',
        globalName,
        target: ['es2019'],
        platform: 'browser',
        legalComments: 'none',
        banner: banner ? {js: banner} : undefined,
        define: {__VERSION__: JSON.stringify(pkg.version), ...defines},
        logLevel: 'warning'
    });
    const stat = await fs.stat(outfile);
    console.log(`built ${path.relative(ROOT, outfile)} (${stat.size} bytes)`);
}

// The userscript shows the same official icon as the native shells. It is
// generated by scripts/generate-icons.py; when the file is missing the bundle
// still builds and the UI falls back to the emoji.
async function iconDataUri() {
    const iconPath = path.join(ROOT, 'mobile/userscript/icon.png');
    try {
        const bytes = await fs.readFile(iconPath);
        return `data:image/png;base64,${bytes.toString('base64')}`;
    } catch (error) {
        console.warn('mobile/userscript/icon.png missing; run `npm run icons` for the bundled icon');
        return '';
    }
}

async function main() {
    const engineEntry = path.join(ROOT, 'mobile/engine/browser.js');
    await build(
        path.join(ROOT, 'mobile/userscript/entry.js'),
        path.join(ROOT, 'dist/instaling-bot.user.js'),
        {banner: USERSCRIPT_HEADER, defines: {__ICON__: JSON.stringify(await iconDataUri())}}
    );
    await build(engineEntry, path.join(ROOT, 'mobile/android/app/src/main/assets/core.js'));
    await build(engineEntry, path.join(ROOT, 'mobile/ios/InstalingBot/Resources/core.js'));
}

main().catch(error => {
    console.error(error);
    process.exit(1);
});
